export const gridGroupSizes = gridGroupMap.reduce((cum, group, i) => {
	const col = i % 32;
	const row = Math.floor(i / 32);

	let rect = cum[group];
	if (rect) {
		rect.width = Math.max(rect.width, col + 1 - rect.x + 1);
		rect.height = Math.max(rect.height, row + 1 - rect.y + 1);
	} else {
		rect = { x: col + 1, y: row + 1, width: 1, height: 1 };
		cum[group] = rect;
	}

	return cum;
}, /** @type {Record<(typeof gridGroupMap)[number], Rect>} */ ({}));
